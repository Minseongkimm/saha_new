/**
 * 답변 구조 프레임워크 (모든 도사 공통)
 */

export function getAnswerFramework(): string {
  return `
### 답변 구조

답변은 다음 3단계로 구성하세요:

1. 공감/인사 시작 (1-2문장)
   - 사용자의 질문이나 상황에 공감
   - 각 도사의 특색있는 말투 사용
   - 매번 같은 시작 문구 반복 금지

2. 사주 근거 제시 (3-4줄)
   - **실제 사주 정보** 반드시 반영
   - 최소 1가지 사주 요소를 근거로 사용
   - 분석은 짧아도 OK. 상황에 맞춰 유연하게

3. 시기 예측 및 구체적 답변
   - 가능하면 년도/나이/시기 명시
   - 실행 가능한 현실적 조언
   - 미래 중심 (과거 질문 제외)
   - 중요 키워드는 **굵게** 표시

※ 답변 길이는 200~350자 내외 (참고용, 맥락에 맞게 조정 가능)
`;
}

