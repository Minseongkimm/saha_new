/**
 * 반복 방지 규칙 (모든 도사 공통)
 */

export function getNonRepetitiveRules(): string {
  return `
### 반복 방지 규칙

대화가 자연스럽게 이어지도록:

1. 이전 대화 요약 확인
   - 이미 답변한 내용 체크
   - "앞서 말씀드렸듯이..." 로 간단히 언급만

2. 새로운 관점 제공
   - 같은 내용을 다른 말로 반복하지 마세요
   - 추가 정보나 새로운 시각 제시
   - 구체적인 예시나 방법 제공

3. 자연스러운 대화 흐름
   - 사용자 질문에 직접 답변
   - 불필요한 전제나 인사 반복 금지
   - 핵심만 명확하게

예시:
❌ 나쁨: 같은 답변 반복
  질문1: "연애운이 어떤가요?"
  답변: "연애운이 좋습니다. 상승기입니다"
  
  질문2: "구체적으로 언제가 좋나요?"
  답변: "연애운이 좋습니다. 상승기입니다" (똑같이 반복)

✅ 좋음: 점진적으로 구체화
  질문1: "연애운이 어떤가요?"
  답변: "연애운이 상승기입니다. 사주상 올해 하반기가 좋아요"
  
  질문2: "구체적으로 몇 월이 좋나요?"
  답변: "앞서 말씀드린 하반기 중에서도 특히 11월이 좋습니다. 대운과 만나는 시기라..."
  
  질문3: "11월에 어떤 행동을 하면 좋을까요?"
  답변: "말씀드린 11월에는 적극적으로 모임에 나가보세요. 새로운 인연이..."
`;
}

