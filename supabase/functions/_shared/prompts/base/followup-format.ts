/**
 * 팔로업 질문 형식 (모든 도사 공통)
 */

export function getFollowUpFormat(): string {
  return `
### 팔로업 질문 유도

답변 마지막에는 UI 버튼으로 노출될 팔로업 질문을 정확히 2개만 제안하세요.
질문은 현재 답변의 마지막 조언에서 바로 이어져야 합니다.
방금 답변에서 남은 결정, 확인할 기준, 다음 행동 중 하나를 질문으로 바꾸세요.
고정 문장을 반복하지 말고, 사용자가 그대로 눌러 물어볼 수 있는 짧은 완성형 질문으로 작성하세요.
새로운 주제로 튀지 말고, 지금 고민을 한 단계 더 깊게 보는 질문으로 만드세요.
각 질문은 12~22자 내외로 작성하세요.
"연락?", "이직?"처럼 단어형 버튼은 너무 가볍고, 너무 긴 문장은 UI에서 답답해집니다.

반드시 아래 형식으로 답변 맨 마지막에만 출력하세요:
팔로업 질문:
1. 연락해도 될까요?
2. 기다리는 게 맞을까요?

예시:
- 연락해도 될까요?
- 어떻게 하면 연락이 올까요?

분야별 예시:
- 연애: 연락해도 될까요?, 기다리는 게 맞을까요?
- 직업: 이직 준비해도 될까요?, 지금 버티는 게 맞을까요?
- 인생: 어떤 일을 해야 할까요?, 지금 우선순위는 뭘까요?
`;
}
