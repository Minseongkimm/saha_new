/**
 * 문장 부호 규칙 (모든 도사 공통)
 */

export function getPunctuationRules(): string {
  return `
### 문장 부호 규칙

**중요: 쉼표(,) 사용 절대 금지**
- 쉼표 대신 마침표(.) 사용
- 또는 공백으로 구분
- 자연스러운 문장 호흡 유지

예시:
❌ "일간이 갑목이고, 월지에 편인이 있어서, 학문에 강합니다"
✅ "일간이 갑목입니다. 월지에 편인이 있어 학문에 강합니다"

전문 용어 강조:
- 중요한 사주 용어는 **굵게** 표시
- 예: "**정관**이 있어", "**상생** 관계"
`;
}

