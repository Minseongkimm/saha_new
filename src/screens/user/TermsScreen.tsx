const TermsScreen: React.FC<TermsScreenProps> = ({ navigation, route }) => {
  const { type } = route.params || { type: 'terms' }; // 'terms' or 'privacy'

  const getTitle = () => {
    return type === 'privacy' ? '개인정보처리방침' : '이용약관';
  };

  const getContent = (): string => {
    return type === 'privacy' ? PRIVACY_POLICY : TERMS_OF_SERVICE;
  };

  return (
    <SafeAreaView style={styles.container}>
      <CustomHeader 
        title={getTitle()}
        onBackPress={() => safeGoBack(navigation)}
      />
      <ScrollView style={styles.scrollView} contentContainerStyle={styles.contentContainer}>
        <Text style={styles.content}>{getContent()}</Text>
      </ScrollView>
    </SafeAreaView>
  );
};

